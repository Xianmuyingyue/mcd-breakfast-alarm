def main() -> int:
    seen, menu = set(), []
    for code, name, price, orig, disc, kw, img in ITEMS:
        if code in seen:
            continue
        seen.add(code)
        menu.append({"c": code, "n": name, "p": price, "o": orig,
                     "d": disc, "t": kw, "i": BASE + img})

    bd = json.load(open("/tmp/bless_data.json", encoding="utf-8"))

    tpl = open(os.path.join(HERE, "app.tpl.html"), encoding="utf-8").read()
    html = (tpl
            .replace("__MENU_JSON__", json.dumps(menu, ensure_ascii=False, separators=(",", ":")))
            .replace("__BLESS_JSON__", json.dumps(bd["blessings"], ensure_ascii=False, separators=(",", ":")))
            .replace("__BIDX_JSON__", json.dumps(bd["idx"], ensure_ascii=False))
            .replace("__BSTART_JSON__", json.dumps(bd["start"], ensure_ascii=False)))

    out = os.path.join(HERE, "index.html")
    open(out, "w", encoding="utf-8").write(html)

    # 单独留一份菜单快照，方便审阅
    snap = {
        "source": "麦克唐纳官方 MCP query-meals",
        "storeCode": "1450104",
        "fetchedAt": "2026-10-22 07:56 (北京时间)",
        "note": "disc=1 表示该价格需随单购早餐卡；实际成交价以官方 MCP 实时核价为准。",
        "count": len(menu),
        "items": menu,
    }
    json.dump(snap, open(os.path.join(HERE, "menu-snapshot.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    print(f"OK  {out}")
    print(f"    {len(html):,} bytes | {len(menu)} 个早餐 SKU | {len(bd['blessings'])} 句麦言麦语")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
